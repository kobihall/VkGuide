#!/usr/bin/env python3
"""Writes the Halton sampler's constant tables, once for C++ and once for GLSL, so both read the
same numbers:  python3 tools/sampler_tables/generate_halton_tables.py

For each of the first 200 primes (a sample dimension's base): the prime, its reciprocal as a float
(a GPU's division is not IEEE, so a shader must not compute 1 / base itself), and how many digits
pbrt-v4's ScrambledRadicalInverse() and OwenScrambledRadicalInverse() loop over. Both loops stop
when the float 1 - (base - 1) * base^-m (or 1 - base^-m) stops being below 1, a float comparison
that a GPU compiler may fuse differently, so the count is tabulated from float32 arithmetic here
instead of being re-evaluated in a shader.
"""
import numpy as np
from pathlib import Path

COUNT = 200
primes = []
n = 2
while len(primes) < COUNT:
    if all(n % p for p in primes if p * p <= n):
        primes.append(n)
    n += 1

f32 = np.float32


def scrambled_digits(base):
    inverse, m, digits = f32(1) / f32(base), f32(1), 0
    while f32(1) - f32(base - 1) * m < f32(1):
        digits += 1
        m = f32(m * inverse)
    return digits


def owen_digits(base):
    inverse, m, digits = f32(1) / f32(base), f32(1), 0
    while f32(1) - m < f32(1):
        digits += 1
        m = f32(m * inverse)
    return digits


inverses = [f32(1) / f32(b) for b in primes]
scrambled = [scrambled_digits(b) for b in primes]
owen = [owen_digits(b) for b in primes]

root = Path(__file__).resolve().parents[2]


def rows(values, per_line=16):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("\t" + ", ".join(str(v) for v in values[i:i + per_line]))
    return ",\n".join(lines)


(root / "src" / "sampler_halton_tables.h").write_text(f"""#pragma once

// GENERATED by tools/sampler_tables/generate_halton_tables.py. Do not edit.
// The Halton sampler's bases and digit counts; shaders/rt/include/crt_halton_tables.glsl is the same data.

#include <cstdint>

inline constexpr uint32_t HALTON_DIMENSIONS = {COUNT};

inline constexpr uint32_t HALTON_PRIMES[HALTON_DIMENSIONS] = {{
{rows(primes)}
}};

// 1 / prime in float, rounded as IEEE division rounds it
inline constexpr float HALTON_INVERSE_PRIMES[HALTON_DIMENSIONS] = {{
{rows([f"{float(v):.9g}f" for v in inverses])}
}};

// the digits ScrambledRadicalInverse() loops over for each base
inline constexpr uint8_t HALTON_SCRAMBLED_DIGITS[HALTON_DIMENSIONS] = {{
{rows(scrambled)}
}};

// and OwenScrambledRadicalInverse()
inline constexpr uint8_t HALTON_OWEN_DIGITS[HALTON_DIMENSIONS] = {{
{rows(owen)}
}};
""")

(root / "shaders" / "rt" / "include" / "crt_halton_tables.glsl").write_text(f"""// GENERATED by tools/sampler_tables/generate_halton_tables.py. Do not edit.
// The Halton sampler's bases and digit counts; src/sampler_halton_tables.h is the same data.

#define CRT_HALTON_DIMENSIONS {COUNT}u

const uint CRT_HALTON_PRIMES[CRT_HALTON_DIMENSIONS] = uint[](
{rows([f"{p}u" for p in primes])}
);

// 1 / prime in float, rounded as IEEE division rounds it
const float CRT_HALTON_INVERSE_PRIMES[CRT_HALTON_DIMENSIONS] = float[](
{rows([f"{float(v):.9g}" if "." in f"{float(v):.9g}" or "e" in f"{float(v):.9g}" else f"{float(v):.9g}.0" for v in inverses])}
);

// the digits ScrambledRadicalInverse() loops over for each base
const uint CRT_HALTON_SCRAMBLED_DIGITS[CRT_HALTON_DIMENSIONS] = uint[](
{rows([f"{d}u" for d in scrambled])}
);

// and OwenScrambledRadicalInverse()
const uint CRT_HALTON_OWEN_DIGITS[CRT_HALTON_DIMENSIONS] = uint[](
{rows([f"{d}u" for d in owen])}
);
""")
print("wrote", COUNT, "primes, last", primes[-1])
