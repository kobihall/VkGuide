#!/usr/bin/env python3
"""Renders pbrt-v4's own RGB for spectra bin/spectrum_test checks, and writes tests/spectrum_pbrt_reference.inc.

Each case is a small image pbrt fills with one spectrum, through a box filter, so every pixel's expected value is
the spectrum's RGB: an emitting quad seen head on (a light, after pbrt divides it by its luminance), a diffuse quad
lit by a uniform white sky with only direct light (a reflectance), and a smooth conductor seen through an
orthographic camera reflecting that sky (its Fresnel reflectance at normal incidence). The image's mean is the
reference; with 32 x 32 pixels at 4096 samples its noise is about 1e-4.

pbrt is the user's build: set PBRT, or it is looked for beside this repository and then on the PATH.

Run:  python3 tools/spectrum_tables/pbrt_reference.py
"""

import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_BUILD = ROOT.parent / "pbr-book-website" / "pbrt-v4" / "build"
QUAD = 'Shape "trianglemesh" "integer indices" [0 1 2 0 2 3] "point3 P" [-10 -10 0  10 -10 0  10 10 0  -10 10 0]\n'


def tool(name, env):
    if os.environ.get(env):
        return os.environ[env]
    if (DEFAULT_BUILD / name).exists():
        return str(DEFAULT_BUILD / name)
    found = shutil.which(name)
    if found:
        return found
    sys.exit(f"{name} not found: set {env} or put it on the PATH")


def header(camera, depth):
    return (f'LookAt 0 0 -5  0 0 0  0 1 0\n{camera}\n'
            'Film "rgb" "integer xresolution" 32 "integer yresolution" 32 "string filename" "out.exr"\n'
            'Sampler "independent" "integer pixelsamples" 4096\n'
            'PixelFilter "box" "float xradius" 0.5 "float yradius" 0.5\n'
            f'Integrator "volpath" "integer maxdepth" {depth} "bool regularize" false\n'
            'WorldBegin\n')


def emitter(spectrum):
    return (header('Camera "perspective" "float fov" 20', 1) + 'AttributeBegin\n'
            f'AreaLightSource "diffuse" {spectrum} "bool twosided" true\n'
            'Material "diffuse" "rgb reflectance" [0 0 0]\n' + QUAD + 'AttributeEnd\n')


def reflector(spectrum):
    return (header('Camera "perspective" "float fov" 20', 1) + 'LightSource "infinite" "rgb L" [1 1 1]\n'
            f'Material "diffuse" {spectrum}\n' + QUAD)


def conductor(metal):
    return (header('Camera "orthographic" "float screenwindow" [-1 1 -1 1]', 1) + 'LightSource "infinite" "rgb L" [1 1 1]\n'
            f'Material "conductor" "spectrum eta" "metal-{metal}-eta" "spectrum k" "metal-{metal}-k" "float roughness" 0\n' + QUAD)


# what bin/spectrum_test computes for each, as C++, beside the scene that makes pbrt's
CASES = [
    ("blackbody 2700 K", "glm::dvec3(emissionToRgb(blackbodySpectrum(2700)))", emitter('"blackbody L" [2700]')),
    ("blackbody 6500 K", "glm::dvec3(emissionToRgb(blackbodySpectrum(6500)))", emitter('"blackbody L" [6500]')),
    ("blackbody 1850 K", "glm::dvec3(emissionToRgb(blackbodySpectrum(1850)))", emitter('"blackbody L" [1850]')),
    ("stdillum-A light", "glm::dvec3(emissionToRgb(*namedSpectrum(\"stdillum-A\")))", emitter('"spectrum L" "stdillum-A"')),
    ("stdillum-F11 light", "glm::dvec3(emissionToRgb(*namedSpectrum(\"stdillum-F11\")))", emitter('"spectrum L" "stdillum-F11"')),
    ("rgb light (0.2, 0.5, 0.9)", "glm::dvec3(0.2, 0.5, 0.9)", emitter('"rgb L" [0.2 0.5 0.9]')),
    ("spectral reflectance ramp", "glm::dvec3(reflectanceToRgb(piecewiseLinearSpectrum(std::vector<float> { 400.f, 0.1f, 550.f, 0.6f, 700.f, 0.3f }, false)))",
     reflector('"spectrum reflectance" [400 0.1 550 0.6 700 0.3]')),
    ("gold at normal incidence", "conductorRgb(\"Au\")", conductor("Au")),
    ("copper at normal incidence", "conductorRgb(\"Cu\")", conductor("Cu")),
    ("silver at normal incidence", "conductorRgb(\"Ag\")", conductor("Ag")),
]


def read_pfm(path):
    data = Path(path).read_bytes()
    parts = data.split(b"\n", 3)
    width, height = map(int, parts[1].split())
    scale = float(parts[2])
    count = width * height * 3
    values = struct.unpack(("<" if scale < 0 else ">") + f"{count}f", parts[3][:count * 4])
    return [sum(values[c::3]) / (width * height) for c in range(3)]


def main():
    pbrt = tool("pbrt", "PBRT")
    imgtool = tool("imgtool", "IMGTOOL")
    lines = ["// Generated by tools/spectrum_tables/pbrt_reference.py from pbrt-v4's renders. Do not edit.\n"]
    with tempfile.TemporaryDirectory() as work:
        work = Path(work)
        for name, ours, scene in CASES:
            (work / "scene.pbrt").write_text(scene)
            subprocess.run([pbrt, "--quiet", "--outfile", str(work / "out.exr"), str(work / "scene.pbrt")], check=True, cwd=work)
            subprocess.run([imgtool, "convert", "--outfile", str(work / "out.pfm"), str(work / "out.exr")], check=True, capture_output=True)
            r, g, b = read_pfm(work / "out.pfm")
            print(f"{name}: pbrt ({r:.6f}, {g:.6f}, {b:.6f})")
            lines.append(f'{{ "{name}", {ours}, glm::dvec3({r:.7f}, {g:.7f}, {b:.7f}) }},\n')
    out = ROOT / "tests" / "spectrum_pbrt_reference.inc"
    out.write_text("".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
