#!/usr/bin/env python3
"""Writes src/spectrum_tables.cpp from pbrt-v4's src/pbrt/util/spectrum.cpp.

The CIE 1931 matching functions and every spectrum pbrt-v4 knows by name (standard illuminants, metals' complex
indices of refraction, glasses, camera sensors), copied as pbrt stores them: the matching functions at every
nanometer from 360 to 830, the named spectra as interleaved (wavelength, value) pairs. NAMED_SPECTRA lists each name
with its data and whether pbrt normalizes it to a luminance of 1 (the illuminants), in pbrt's order.

pbrt-v4 is Apache-2.0; the glass data comes from refractiveindex.info (CC0). See src/spectrum.h.

Run:  python3 tools/spectrum_tables/extract_pbrt_spectra.py [--pbrt ../pbr-book-website/pbrt-v4]
"""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def arrays(source):
    """Every `const Float NAME[...] = { ... };` in the file, as lists of number strings."""
    found = {}
    for match in re.finditer(r"const Float (\w+)\[[^\]]*\]\s*=\s*\{(.*?)\};", source, re.S):
        body = re.sub(r"//[^\n]*", "", match.group(2))
        found[match.group(1)] = [v for v in re.split(r"[\s,]+", body) if v]
    return found


def named_spectra(source):
    """pbrt's namedSpectra map in order: (name, array, normalized)."""
    variables = {}
    for match in re.finditer(r"Spectrum (\w+)\s*=\s*PiecewiseLinearSpectrum::FromInterleaved\((\w+), (true|false), alloc\);", source):
        variables[match.group(1)] = (match.group(2), match.group(3) == "true")
    table = re.search(r"namedSpectra = \{(.*?)\};", source, re.S).group(1)
    result = []
    for match in re.finditer(r'\{"([^"]+)",\s*(?:(\w+)\}|PiecewiseLinearSpectrum::FromInterleaved\((\w+), (true|false), alloc\)\})', table):
        name = match.group(1)
        if match.group(2):
            array, normalized = variables[match.group(2)]
        else:
            array, normalized = match.group(3), match.group(4) == "true"
        result.append((name, array, normalized))
    return result


def emit_array(name, values):
    lines = []
    for i in range(0, len(values), 8):
        lines.append("\t" + ", ".join(f"{float(v)!r}f" for v in values[i:i + 8]) + ",")
    return f"const float {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--pbrt", type=Path, default=ROOT.parent / "pbr-book-website" / "pbrt-v4")
    parser.add_argument("--out", type=Path, default=ROOT / "src" / "spectrum_tables.cpp")
    args = parser.parse_args()

    source = (args.pbrt / "src" / "pbrt" / "util" / "spectrum.cpp").read_text()
    data = arrays(source)
    named = named_spectra(source)
    for axis in "XYZ":
        assert len(data[f"CIE_{axis}"]) == 471, axis

    out = [
        "// Generated by tools/spectrum_tables/extract_pbrt_spectra.py from pbrt-v4's src/pbrt/util/spectrum.cpp. Do not edit.\n",
        "// pbrt-v4 is Apache-2.0; the glass data is from refractiveindex.info (CC0).\n\n",
        "#include <spectrum.h>\n\n",
        "#include <iterator>\n\n",
        "namespace spectrum_tables {\n\n",
    ]
    for axis in "XYZ":
        out.append(emit_array(f"CIE_{axis}", data[f"CIE_{axis}"]).replace("const float", "extern const float", 1).replace("[]", "[CIE_SAMPLES]", 1) + "\n")
    used = []
    for _, array, _ in named:
        if array not in used:
            used.append(array)
    out.append("namespace {\n\n")
    for array in used:
        out.append(emit_array(array, data[array]) + "\n")
    out.append("}\n\n")
    out.append("extern const NamedSpectrumData NAMED_SPECTRA[] = {\n")
    for name, array, normalized in named:
        out.append(f'\t{{ "{name}", {array}, std::size({array}) / 2, {"true" if normalized else "false"} }},\n')
    out.append("};\n")
    out.append("extern const size_t NAMED_SPECTRUM_COUNT = std::size(NAMED_SPECTRA);\n\n")
    out.append("}\n")
    args.out.write_text("".join(out))
    print(f"wrote {args.out}: {len(named)} named spectra from {len(used)} tables")


if __name__ == "__main__":
    main()
